// Writes a number as C source. A gain that is not set yet (NaN) becomes 0, so the sketch still compiles.
function num(v) {
  return Number.isFinite(v) ? String(v) : "0";
}

// Returns the Arduino sketch as a string, for { Kp, Ki, Kd, Ts, uMin, uMax, antiWindup }.
// The sketch must run the same formula and the same rules as simulate() in engine.js:
//   u[k] = Kp e[k] + Ki Ts sum(e[0..k]) + Kd (e[k] - e[k-1]) / Ts, with e[-1] = e[0],
//   and anti-windup keeps the old sum when the new sum would put u at its limit.
// A real PWM pin cannot output an unlimited u, so an infinite limit becomes 0..100 (percent).
export function arduinoCode({ Kp, Ki, Kd, Ts, uMin, uMax, antiWindup }) {
  const low = Number.isFinite(uMin) ? uMin : 0;
  const high = Number.isFinite(uMax) ? uMax : 100;
  // Rounded on our side: on an Arduino, float(0.251) * 1000 truncates to 250.
  const tsMs = Math.round(Ts * 1000);
  return `// Digital PID generated by our toolkit (P3). Same formula and rules as the simulator.
// u[k] = Kp e[k] + Ki Ts sum(e[0..k]) + Kd (e[k] - e[k-1]) / Ts
// Kp = ${num(Kp)}, Ki = ${num(Ki)}, Kd = ${num(Kd)}, Ts = ${tsMs} ms, u limited to ${num(low)}..${num(high)}, anti-windup ${antiWindup ? "on" : "off"}

// 1. Constants
const float KP = ${num(Kp)};
const float KI = ${num(Ki)};
const float KD = ${num(Kd)};
const float TS = ${num(tsMs / 1000)};        // sampling time in seconds
const unsigned long TS_MS = ${tsMs};      // the same sampling time in whole milliseconds
const float U_MIN = ${num(low)};
const float U_MAX = ${num(high)};
const bool ANTI_WINDUP = ${antiWindup ? "true" : "false"};
const float SETPOINT = 1.0;     // the target, in the same units as readSensor()
const int ACTUATOR_PIN = 25;    // PWM output, for example PWMA on the TB6612FNG
const int SENSOR_PIN = 34;      // analog input (an ADC1 pin on the ESP32)

// 2. Variables
float sum = 0;                  // sum of e[0..k]
float ePrev = 0;                // e[k-1]
bool first = true;              // true until the first sample sets e[-1] = e[0]
unsigned long lastTime;

// Replace this with the real measurement, for example the motor speed from the encoder.
float readSensor() {
  return analogRead(SENSOR_PIN) / 4095.0;  // 0..1 on the ESP32's 12-bit ADC
}

float clip(float v) {
  if (v < U_MIN) return U_MIN;
  if (v > U_MAX) return U_MAX;
  return v;
}

// 3. setup()
void setup() {
  Serial.begin(115200);
  pinMode(ACTUATOR_PIN, OUTPUT);
  pinMode(SENSOR_PIN, INPUT);
  lastTime = millis();
}

// 4. loop(): the controller runs once every TS_MS, and u is held in between.
void loop() {
  if (millis() - lastTime < TS_MS) return;
  lastTime += TS_MS;              // adding keeps the samples evenly spaced

  // 5. Read the sensor and find the error
  float y = readSensor();
  float e = SETPOINT - y;

  // 6. e[-1] = e[0] on the first sample, so there is no kick from the D term at the start
  if (first) {
    ePrev = e;
    first = false;
  }

  // 7. The PID formula with the new sum, then the limit
  float newSum = sum + e;
  float deriv = (e - ePrev) / TS;
  float raw = KP * e + KI * TS * newSum + KD * deriv;
  float u = clip(raw);

  // 8. Anti-windup: if the new sum puts u at its limit, keep the old sum
  if (ANTI_WINDUP && u != raw) {
    raw = KP * e + KI * TS * sum + KD * deriv;
    u = clip(raw);
  } else {
    sum = newSum;
  }

  // 9. u is in percent and analogWrite takes 0..255
  analogWrite(ACTUATOR_PIN, (int)(u * 255.0 / 100.0));

  // 10. Remember this error for the next D term
  ePrev = e;

  Serial.print(y, 4);
  Serial.print(',');
  Serial.println(u, 4);
}
`;
}
